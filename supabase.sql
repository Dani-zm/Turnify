CREATE TABLE IF NOT EXISTS registro_beta (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nombre VARCHAR(100) NOT NULL,              -- nombre
    correo VARCHAR(150) NOT NULL,              -- correo
    tipo_negocio VARCHAR(100) NOT NULL,        -- perfil o empresa
    necesidad_principal TEXT,                  -- necesidad
    plan_interes VARCHAR(50) DEFAULT 'Plan Gratuito ($0)',  -- interés
    fecha_inscripcion TIMESTAMP WITH TIME ZONE DEFAULT NOW() -- fecha de inscripción
);

-- Row Level Security: el público puede INSERTAR, no puede LEER
ALTER TABLE registro_beta ENABLE ROW LEVEL SECURITY;

CREATE POLICY "Publico puede registrarse en la beta"
  ON registro_beta FOR INSERT
  TO anon
  WITH CHECK (true);

-- No se crea ninguna política de SELECT: nadie desde la web puede leer los datos.
