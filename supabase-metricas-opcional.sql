CREATE TABLE IF NOT EXISTS eventos_landing (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    sesion VARCHAR(80) NOT NULL,
    tipo VARCHAR(50) NOT NULL,
    detalle VARCHAR(120),
    fecha TIMESTAMP WITH TIME ZONE DEFAULT NOW()
);
ALTER TABLE eventos_landing ENABLE ROW LEVEL SECURITY;
CREATE POLICY "Publico puede enviar eventos"
  ON eventos_landing FOR INSERT TO anon WITH CHECK (true);
